def choose_lines(risk: str, serial: int, substance: str = "") -> tuple[str, str]:
    """Rotate cleanly among authored black-humor lines with substance callbacks.

    One of every three turns focuses on the current substance. There are no
    chatbot-branded punchlines or risk-management slogans inside the photo.
    """
    if serial < 1:
        raise ValueError("Serial must be positive")
    if serial % 7 == 1:
        phrases = ONE_LINERS.get(risk, ONE_LINERS["general"])
        return "", phrases[(serial // 7) % len(phrases)]
    if serial % 11 == 4:
        phrases = ABSURD.get(risk, ABSURD["general"])
        return phrases[(serial // 11) % len(phrases)]
    if serial % 3 == 0 and substance in SUBSTANCE_LINES:
        phrases = SUBSTANCE_LINES[substance]
        return phrases[(serial // 3 - 1) % len(phrases)]
    phrases = LINES.get(risk, LINES["general"])
    return phrases[(serial - 1) % len(phrases)]
