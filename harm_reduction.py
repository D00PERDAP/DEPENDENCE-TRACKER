DISCLAIMER = "\n\nЭто общая информация, не диагноз. При ухудшении или сомнениях обращайся за экстренной помощью."

@dataclass(frozen=True)
class Card:
    title: str
    text: str
    urgent: bool


def emergency(substance, symptom):
    details = ""
    if substance in STIMULANTS or substance == "MDMA":
        details = "\n\nПосле стимуляторов боль в груди, сильный перегрев, судороги и спутанность особенно опасны."
    elif substance in SEDATIVES:
        details = "\n\nПри опиоидах, алкоголе или седативных веществах особенно опасны сонливость и замедленное дыхание."
    return Card("🆘 Нужна срочная помощь", EMERGENCY_TEXT + details, True)


def get_card(substance, symptom):
    """Fail closed: unknown symptoms are treated as an emergency, not dismissed."""
    substance = substance if substance in SUBSTANCES else "Другое / не знаю"
    if symptom in EMERGENCY or symptom not in {x[0] for x in SYMPTOMS}:
        return emergency(substance, symptom)

    common = (
        "Не принимай больше веществ и не пытайся «перебить» эффект алкоголем, "
        "таблетками или другими средствами. Попроси трезвого человека побыть рядом."
    )
    if symptom == "panic":
        advice = (
            "Если нет боли в груди, затруднения дыхания, судорог, перегрева или выраженной спутанности: "
            "перейди в тихое безопасное место и попробуй медленно дышать. " + common
        )
        if substance in STIMULANTS:
            advice += "\n\nПосле стимуляторов тревога и учащённое сердцебиение могут быть связаны с серьёзными осложнениями: не списывай тяжёлые симптомы на обычную панику."
        if substance == "Каннабис":
            advice += "\n\nПосле каннабиса тревога может быть выраженной; если состояние не проходит или усиливается — нужна медицинская оценка."
        return Card("😰 Тревога / паника", advice + DISCLAIMER, False)
    if symptom == "confused":
        if substance == "Альфа-ПВП" or substance in STIMULANTS:
            advice = ("Сильная паранойя, потеря связи с реальностью или выраженная спутанность после стимуляторов "
                      "могут требовать экстренной помощи. Если не можешь безопасно оценить ситуацию — звони в скорую. ")
        else:
            advice = ("Если выраженная спутанность, галлюцинации с потерей ориентировки, агрессия "
                      "или риск причинить себе вред — обращайся за экстренной помощью. ")
        return Card("🌀 Паранойя / спутанность",
                    advice + "Перейди в безопасное спокойное место. " + common + DISCLAIMER, False)
    if symptom == "sleep":
        advice = (
            "Не пытайся «вырубить себя» алкоголем, снотворными или другими веществами. "
            "Убери яркий свет и стимулы, по возможности попроси трезвого человека побыть рядом."
        )
        if substance in STIMULANTS:
            advice += "\n\nДлительное бодрствование вместе с сильной тревогой, бредом, болью в груди или перегревом — повод для срочной оценки врачом."
        return Card("😵 Не могу спать", advice + DISCLAIMER, False)
    if symptom == "nausea":
        advice = (
            "При многократной рвоте, невозможности пить, сильной слабости, нарушении сознания, "
            "судорогах или ухудшении — вызывай скорую. "
            "Если полностью в сознании и можешь безопасно глотать — небольшие глотки воды, "
            "но не пей литрами залпом, особенно после MDMA. " + common
        )
        if substance in SEDATIVES:
            advice += "\n\nПри сильной сонливости после опиоидов или седативных средств не оставляй человека одного: возможны опасные нарушения дыхания."
        return Card("🤢 Тошнота / слабость", advice + DISCLAIMER, False)
    return emergency(substance, symptom)


